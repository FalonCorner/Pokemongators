"""Builds data/pokemon.js from PokeAPI CSVs (github.com/PokeAPI/pokeapi/tree/master/data/v2/csv).

Usage: python3 tools/build_data.py <dir-with-csvs>
Needs pokemon_species.csv, pokemon_species_names.csv, pokemon_types.csv.
"""
import csv, json, sys, os
from collections import defaultdict

src = sys.argv[1]
out = os.path.join(os.path.dirname(__file__), "..", "data", "pokemon.js")

def rows(name):
    with open(os.path.join(src, name), newline="", encoding="utf-8") as f:
        yield from csv.DictReader(f)

names = {int(r["pokemon_species_id"]): r["name"] for r in rows("pokemon_species_names.csv") if r["local_language_id"] == "9"}
types = defaultdict(list)
for r in rows("pokemon_types.csv"):
    pid = int(r["pokemon_id"])
    if pid < 10000:
        types[pid].append((int(r["slot"]), int(r["type_id"])))

species = {}
for r in rows("pokemon_species.csv"):
    i = int(r["id"])
    species[i] = dict(id=i, gen=int(r["generation_id"]),
                      parent=int(r["evolves_from_species_id"]) if r["evolves_from_species_id"] else None,
                      chain=int(r["evolution_chain_id"]),
                      legend=r["is_legendary"] == "1" or r["is_mythical"] == "1")

def depth(i):
    d, p = 0, species[i]["parent"]
    while p:
        d, p = d + 1, species[p]["parent"]
    return d

# A "family" = species of one generation that share an evolution chain.
fams = defaultdict(list)
for s in species.values():
    fams[(s["gen"], s["chain"])].append(s["id"])

families = []
for (gen, chain), ids in fams.items():
    ids.sort(key=lambda i: (depth(i), i))
    families.append(dict(g=gen, m=ids))
families.sort(key=lambda f: min(f["m"]))

poke = {i: [names[i], [t for _, t in sorted(types[i])], 1 if s["legend"] else 0] for i, s in species.items()}

with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by tools/build_data.py from PokeAPI data. Do not edit by hand.\n")
    f.write("window.POKEDEX = " + json.dumps({"p": poke, "f": families}, separators=(",", ":"), ensure_ascii=False) + ";\n")
print(len(poke), "species,", len(families), "families ->", out)
